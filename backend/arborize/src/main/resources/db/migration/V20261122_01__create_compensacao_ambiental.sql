CREATE TABLE termos_compensacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razao_social VARCHAR(180) NOT NULL,
    cnpj VARCHAR(14) NOT NULL,
    numero_termo VARCHAR(60),
    data_assinatura DATE,
    prazo_entrega DATE,
    quantidade_acordada INTEGER NOT NULL,
    status VARCHAR(24) NOT NULL,
    termo_objeto VARCHAR(255) NOT NULL UNIQUE,
    termo_content_type VARCHAR(64) NOT NULL,
    termo_nome VARCHAR(255) NOT NULL,
    termo_size_bytes BIGINT NOT NULL,
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP NOT NULL,
    CONSTRAINT ck_termos_compensacao_quantidade CHECK (quantidade_acordada > 0),
    CONSTRAINT ck_termos_compensacao_status CHECK (status IN ('EM_ABERTO', 'PARCIALMENTE_DOADO', 'TOTALMENTE_DOADO')),
    CONSTRAINT ck_termos_compensacao_termo_size CHECK (termo_size_bytes BETWEEN 1 AND 10485760)
);

CREATE INDEX idx_termos_compensacao_razao_social ON termos_compensacao (razao_social);

CREATE TABLE entregas_compensacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    termo_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    recibo_objeto VARCHAR(255) NOT NULL UNIQUE,
    recibo_nome VARCHAR(255) NOT NULL,
    recibo_content_type VARCHAR(64) NOT NULL,
    recibo_size_bytes BIGINT NOT NULL,
    criado_em TIMESTAMP NOT NULL,
    CONSTRAINT fk_entregas_compensacao_termo FOREIGN KEY (termo_id) REFERENCES termos_compensacao (id),
    CONSTRAINT ck_entregas_compensacao_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_entregas_compensacao_recibo_size CHECK (recibo_size_bytes BETWEEN 1 AND 2097152)
);

CREATE INDEX idx_entregas_compensacao_termo_criado ON entregas_compensacao (termo_id, criado_em, id);
