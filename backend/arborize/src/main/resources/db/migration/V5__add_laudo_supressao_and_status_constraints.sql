CREATE TABLE laudos_supressao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id bigint NOT NULL,
    especie_reposicao_id bigint NOT NULL,
    parecer varchar(80) NOT NULL,
    tipo_justificativa varchar(80) NOT NULL,
    justificativa text NOT NULL,
    data_vistoria date NOT NULL,
    pdf_objeto varchar(512) NOT NULL,
    pdf_nome_original varchar(255) NOT NULL,
    pdf_content_type varchar(100) NOT NULL,
    pdf_tamanho_bytes bigint NOT NULL,
    emitido_por_id bigint NOT NULL,
    criado_em timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_laudo_supressao_solicitacao UNIQUE (solicitacao_id),
    CONSTRAINT fk_laudo_supressao_solicitacao
        FOREIGN KEY (solicitacao_id) REFERENCES solicitacoes_substituicao (id),
    CONSTRAINT fk_laudo_supressao_especie_reposicao
        FOREIGN KEY (especie_reposicao_id) REFERENCES especies (id),
    CONSTRAINT fk_laudo_supressao_emitido_por
        FOREIGN KEY (emitido_por_id) REFERENCES usuarios (id)
);
