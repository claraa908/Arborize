ALTER TABLE solicitacoes_substituicao
    ADD CONSTRAINT chk_solicitacoes_substituicao_status
    CHECK (status IN (
        'RECEBIDA',
        'EM_ANALISE',
        'APROVADA',
        'REJEITADA',
        'LAUDO_EMITIDO',
        'RETIRADA_EM_ANDAMENTO',
        'REPLANTIO_EM_ANDAMENTO',
        'CONCLUIDA'
    ));

