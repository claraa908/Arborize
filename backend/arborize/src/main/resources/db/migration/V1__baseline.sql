-- Baseline do esquema existente gerado a partir do mapeamento JPA atual.
-- Em bancos existentes, marque a versão 1 com Flyway baseline; não execute este DDL sobre dados existentes.
CREATE TABLE arvores (
    altura_estimada_m NUMERIC,
    dap_cm NUMERIC,
    data_plantio date,
    latitude NUMERIC NOT NULL,
    longitude NUMERIC NOT NULL,
    atualizado_em timestamp(6) NOT NULL,
    bairro_id bigint,
    criado_em timestamp(6) NOT NULL,
    especie_id bigint NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    bairro_nome TEXT,
    cep TEXT,
    classificacao_territorial varchar(255) NOT NULL CHECK (classificacao_territorial IN ('BAIRRO_IDENTIFICADO','BAIRRO_NAO_IDENTIFICADO','FORA_DA_AREA_URBANA')),
    condicao_fitossanitaria varchar(255) NOT NULL CHECK (condicao_fitossanitaria IN ('NAO_AVALIADA','APARENTEMENTE_SAUDAVEL','SINAIS_COMPROMETIMENTO','MORTA')),
    localidade_rural TEXT,
    observacoes TEXT,
    referencia_localizacao TEXT,
    PRIMARY KEY (id)
);

CREATE TABLE bairros (
    ativo boolean NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    nome varchar(255) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE document (
    created_at timestamp(6),
    educational_material_id bigint,
    especie_id bigint,
    evento_id bigint,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    size_bytes bigint,
    content_type varchar(255),
    extension varchar(255),
    file_path varchar(255) NOT NULL,
    original_filename varchar(255) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE eco_ponto_transactions (
    bottles_collected integer NOT NULL,
    confirmed boolean NOT NULL,
    transaction_date date NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (id)
);

CREATE TABLE educational_materials (
    upload_date date,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    category varchar(255) NOT NULL CHECK (category IN ('ARBORIZACAO_URBANA','CAATINGA','EDUCACAO_AMBIENTAL','LEGISLACAO')),
    description TEXT,
    material_type varchar(255) NOT NULL CHECK (material_type IN ('CARTILHA','MANUAL','RELATORIO_TECNICO','GUIA','OUTROS')),
    status varchar(255) NOT NULL,
    title varchar(255) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE especies (
    mudas_disponiveis integer CHECK (mudas_disponiveis >= 0),
    recomendada_calcadas boolean NOT NULL,
    tempo_germinacao_dias integer,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    categoria varchar(255) NOT NULL,
    descricao_cultivo TEXT,
    familia_botanica varchar(255),
    nome_cientifico varchar(255) NOT NULL,
    nome_popular varchar(255) NOT NULL,
    porte_arvore varchar(255) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE eventos (
    data_inicio date NOT NULL,
    data_termino date NOT NULL,
    horario_inicio time(0) NOT NULL,
    horario_termino time(0) NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    descricao varchar(1000) NOT NULL,
    descricao_encerramento varchar(255),
    descricao_ponto_partida varchar(255),
    destino_final varchar(255),
    local_concentracao varchar(255) NOT NULL,
    nome varchar(255) NOT NULL,
    status varchar(255),
    PRIMARY KEY (id)
);

CREATE TABLE fotos_arvores (
    arvore_id bigint NOT NULL,
    criado_em timestamp(6) NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    size_bytes bigint NOT NULL,
    content_type varchar(255) NOT NULL,
    objeto varchar(255) NOT NULL UNIQUE,
    PRIMARY KEY (id)
);

CREATE TABLE metas_zoneamento (
    ano integer NOT NULL,
    planting_target integer NOT NULL CHECK (planting_target >= 0),
    trimestre integer NOT NULL CHECK (trimestre <= 4 AND trimestre >= 1),
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    bairro varchar(255) NOT NULL,
    zona varchar(255) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_meta_zoneamento_periodo_bairro UNIQUE (ano, trimestre, zona, bairro)
);

CREATE TABLE muda_transactions (
    confirmed boolean NOT NULL,
    quantity integer NOT NULL,
    transaction_date date NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (id)
);

CREATE TABLE plantios (
    confirmed boolean NOT NULL,
    occurred_at date NOT NULL,
    quantity integer NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    bairro varchar(255) NOT NULL,
    species_name varchar(255) NOT NULL,
    zona varchar(255) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE solicitacoes_muda (
    quantidade_mudas integer NOT NULL,
    total_recicaveis integer NOT NULL,
    criada_em timestamp(6) NOT NULL,
    especie_id bigint NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    cpf varchar(11) NOT NULL,
    telefone varchar(11) NOT NULL,
    numero_endereco varchar(30) NOT NULL,
    status varchar(40) NOT NULL CHECK (status IN ('PENDENTE_RECICLAVEIS')),
    bairro varchar(100) NOT NULL,
    complemento varchar(180),
    logradouro varchar(180) NOT NULL,
    nome_solicitante varchar(180) NOT NULL,
    ponto_referencia varchar(255) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE supressoes (
    authorized boolean NOT NULL,
    occurred_at date NOT NULL,
    quantity integer NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    bairro varchar(255) NOT NULL,
    removed_species varchar(255) NOT NULL,
    replacement_species varchar(255),
    zona varchar(255) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE usuarios (
    data_cadastro timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    cpf varchar(11) NOT NULL,
    role varchar(32) DEFAULT 'CIDADAO' NOT NULL CHECK (role IN ('CIDADAO','ADMINISTRADOR_AMMA','FUNCIONARIO_AMMA','AMMA','GESTOR_IFCE','IFCE_GESTOR','BOLSISTA_IFCE','IFCE_BOLSISTA')),
    email varchar(255) NOT NULL,
    endereco varchar(255) NOT NULL,
    nome varchar(255) NOT NULL,
    senha varchar(255) NOT NULL,
    whatsapp varchar(255) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_usuarios_cpf UNIQUE (cpf),
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE INDEX idx_arvores_bairro ON arvores (bairro_id);
CREATE INDEX idx_eco_ponto_transaction_date_confirmed ON eco_ponto_transactions (transaction_date, confirmed);
CREATE INDEX idx_fotos_arvore ON fotos_arvores (arvore_id);
CREATE INDEX idx_muda_transaction_date_confirmed ON muda_transactions (transaction_date, confirmed);
CREATE INDEX idx_plantio_zone_date_confirmed ON plantios (zona, bairro, occurred_at, confirmed);
CREATE INDEX idx_supressao_zone_date_authorized ON supressoes (zona, bairro, occurred_at, authorized);

ALTER TABLE arvores ADD CONSTRAINT fk_arvores_bairro FOREIGN KEY (bairro_id) REFERENCES bairros;
ALTER TABLE arvores ADD CONSTRAINT fk_arvores_especie FOREIGN KEY (especie_id) REFERENCES especies;
ALTER TABLE document ADD CONSTRAINT fk_document_material FOREIGN KEY (educational_material_id) REFERENCES educational_materials;
ALTER TABLE document ADD CONSTRAINT fk_document_especie FOREIGN KEY (especie_id) REFERENCES especies;
ALTER TABLE document ADD CONSTRAINT fk_document_evento FOREIGN KEY (evento_id) REFERENCES eventos;
ALTER TABLE fotos_arvores ADD CONSTRAINT fk_fotos_arvore FOREIGN KEY (arvore_id) REFERENCES arvores;
ALTER TABLE solicitacoes_muda ADD CONSTRAINT fk_solicitacoes_muda_especie FOREIGN KEY (especie_id) REFERENCES especies;
