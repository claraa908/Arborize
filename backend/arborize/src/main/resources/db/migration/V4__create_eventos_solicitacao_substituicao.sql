
-- 1. Tabela principal de solicitações de substituição botânica

CREATE TABLE solicitacoes_substituicao (
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                           protocolo VARCHAR(32) NOT NULL,
                                           nome_solicitante VARCHAR(180) NOT NULL,
                                           cpf VARCHAR(11) NOT NULL,
                                           telefone VARCHAR(11) NOT NULL,
                                           logradouro VARCHAR(180) NOT NULL,
                                           numero_endereco VARCHAR(30) NOT NULL,
                                           bairro VARCHAR(100) NOT NULL,
                                           complemento VARCHAR(180),
                                           ponto_referencia VARCHAR(255) NOT NULL,

                                           descricao_arvore TEXT NOT NULL,
                                           status VARCHAR(40) NOT NULL,

                                           foto_objeto VARCHAR(512),
                                           foto_nome_original VARCHAR(255),
                                           foto_content_type VARCHAR(100),
                                           foto_tamanho_bytes BIGINT,

                                           criada_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
                                           atualizada_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,

                                           CONSTRAINT uk_solicitacao_substituicao_protocolo
                                               UNIQUE (protocolo)
);

-- Índice definido na entidade SolicitacaoSubstituicao

CREATE INDEX idx_solicitacao_substituicao_status_data
    ON solicitacoes_substituicao (status, criada_em);


-- 2. Tabela de eventos das solicitações

CREATE TABLE eventos_solicitacao_substituicao (
                                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                                  solicitacao_id BIGINT NOT NULL,
                                                  status VARCHAR(40) NOT NULL,
                                                  descricao VARCHAR(500) NOT NULL,
                                                  publico BOOLEAN NOT NULL,
                                                  responsavel_id BIGINT,
                                                  criado_em TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,

                                                  CONSTRAINT fk_evento_solicitacao
                                                      FOREIGN KEY (solicitacao_id)
                                                          REFERENCES solicitacoes_substituicao(id),

                                                  CONSTRAINT fk_evento_responsavel
                                                      FOREIGN KEY (responsavel_id)
                                                          REFERENCES usuarios(id)
);
