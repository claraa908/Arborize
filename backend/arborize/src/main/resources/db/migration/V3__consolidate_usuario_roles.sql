ALTER TABLE usuarios DROP CONSTRAINT IF EXISTS usuarios_role_check;

UPDATE usuarios
SET role = CASE role
    WHEN 'AMMA' THEN 'FUNCIONARIO_AMMA'
    WHEN 'IFCE_GESTOR' THEN 'GESTOR_IFCE'
    WHEN 'IFCE_BOLSISTA' THEN 'BOLSISTA_IFCE'
END
WHERE role IN ('AMMA', 'IFCE_GESTOR', 'IFCE_BOLSISTA');

ALTER TABLE usuarios
    ADD CONSTRAINT chk_usuarios_role_canonical
    CHECK (role IN ('CIDADAO', 'ADMINISTRADOR_AMMA', 'FUNCIONARIO_AMMA', 'GESTOR_IFCE', 'BOLSISTA_IFCE'));
