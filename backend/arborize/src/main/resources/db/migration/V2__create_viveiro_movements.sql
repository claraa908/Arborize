CREATE TABLE movimentacoes_mudas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo varchar(32) NOT NULL CHECK (tipo IN ('ENTRADA_GERMINACAO', 'SAIDA_PLANTIO', 'BAIXA_PERDA')),
    quantidade integer NOT NULL CHECK (quantidade > 0),
    data date NOT NULL,
    destino varchar(180),
    responsavel varchar(160),
    observacoes text,
    especie_id bigint NOT NULL,
    comprovante_id bigint UNIQUE,
    CONSTRAINT fk_movimentacao_especie FOREIGN KEY (especie_id) REFERENCES especies (id) ON DELETE RESTRICT,
    CONSTRAINT fk_movimentacao_comprovante FOREIGN KEY (comprovante_id) REFERENCES document (id) ON DELETE RESTRICT
);

CREATE INDEX idx_movimentacao_data ON movimentacoes_mudas (data DESC);
CREATE INDEX idx_movimentacao_especie ON movimentacoes_mudas (especie_id);
CREATE INDEX idx_movimentacao_tipo ON movimentacoes_mudas (tipo);
